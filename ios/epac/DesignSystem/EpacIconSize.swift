import CoreFoundation

// SF Symbol and image frame sizes. Use `.frame(width: EpacIconSize.m, height: EpacIconSize.m)`
// on Image views so icon dimensions are consistent across the app.

enum EpacIconSize {
    static let xs: CGFloat = 16
    static let s: CGFloat = 20
    static let m: CGFloat = 24
    static let l: CGFloat = 32
    static let xl: CGFloat = 48
}
